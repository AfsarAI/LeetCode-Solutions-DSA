class Solution {
    public long countCommas(long n) {

        if(n < 1000)
            return 0;

        if(n < 1000000)
            return n - 999;

        if(n < 1000000000L)
            return 999000L
                 + 2L * (n - 999999L);

        if(n < 1000000000000L)
            return 999000L
                 + 2L * (999999999L - 999999L)
                 + 3L * (n - 999999999L);

        if(n < 1000000000000000L)
            return 999000L
                 + 2L * (999999999L - 999999L)
                 + 3L * (999999999999L - 999999999L)
                 + 4L * (n - 999999999999L);

        return 999000L
             + 2L * (999999999L - 999999L)
             + 3L * (999999999999L - 999999999L)
             + 4L * (999999999999999L - 999999999999L)
             + 5L * (n - 999999999999999L);
    }
}